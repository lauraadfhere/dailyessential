/**
 * Turn scripts/translation-catalog.json into a typed TS module the app imports.
 *
 * Usage: node scripts/generate-catalog-module.js
 */
const fs = require('fs');
const path = require('path');

const input = path.join(__dirname, 'translation-catalog.json');
const output = path.join(__dirname, '..', 'src', 'lib', 'i18n', 'catalog.ts');

const catalog = JSON.parse(fs.readFileSync(input, 'utf8'));
const ar = catalog.ar || {};
const fr = catalog.fr || {};

const keys = [...new Set([...Object.keys(ar), ...Object.keys(fr)])].sort((a, b) => a.localeCompare(b));

const quote = value => JSON.stringify(String(value));

const lines = keys
  .filter(key => {
    const arabic = ar[key];
    const french = fr[key];
    const usable = (value) => typeof value === 'string' && value.trim() && value.trim() !== key.trim();
    return usable(french) || usable(arabic);
  })
  .map(key => `  ${quote(key)}: { fr: ${quote(fr[key] || key)}, ar: ${quote(ar[key] || key)} },`);

const module = `// Generated by scripts/build-translation-catalog.js — edit the source phrases, not this file.
// ${lines.length} interface phrases translated into French and Arabic.
import type { Locale } from './config';

type Translation = { fr: string; ar: string };

export const catalog: Record<string, Translation> = {
${lines.join('\n')}
};
`;

fs.writeFileSync(output, module);
console.log(`wrote ${lines.length} phrases to ${path.relative(process.cwd(), output)}`);
